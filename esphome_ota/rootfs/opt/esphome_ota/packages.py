"""Generate the ESPHome packages users include in their device configs.

Three files in ``ota_server/``, each named for exactly what it contains —
the filename *is* the choice, no need to open it to know what you're
including:

* ``update.yaml`` — an ``update:`` entity only. Recommended: version
  tracking + an Install button in HA. The device reports
  ESPHOME_PROJECT_VERSION as its current version, so the config should
  declare an ``esphome.project`` block or HA will compare against the
  ESPHome release string instead.
* ``flash_button.yaml`` — a force-install button only. No version
  comparison; press it and the current published firmware is installed.
  The fallback for the rare case a proxy/CDN in front of Home Assistant
  mangles the Update entity's JSON manifest fetch (gzip compression, seen
  with some Cloudflare configurations — see DOCS.md).
* ``ota.yaml`` — both together, for a device that wants both entities.
  Only exists because ``update.yaml`` and ``flash_button.yaml`` can't be
  ``!include``d in the same device config — both declare ``http_request:``/
  ``ota:``, and ESPHome doesn't merge two packages' same-named top-level
  keys.
"""

from __future__ import annotations

import logging
from pathlib import Path

LOG = logging.getLogger("packages")

PACKAGE_DIR = "ota_server"
PACKAGE_FILE = "ota.yaml"
UPDATE_FILE = "update.yaml"
BUTTON_FILE = "flash_button.yaml"

HEADER = """\
# ---------------------------------------------------------------------------
# Generated by the ESPHome OTA Publisher add-on. Do not edit — it is rewritten
# whenever the add-on starts or its options change.
# ---------------------------------------------------------------------------
"""

UPDATE_PACKAGE = """\
{header}
# For devices ESPHome's own local/mDNS OTA can't reach (typically: outside
# your LAN, reachable only through your remote/cloud-tunnel URL). A device on
# the same network as Home Assistant should just use ESPHome's built-in OTA —
# it doesn't need this at all.
#
# Adds an "Update" entity: version comparison, Install button in HA.
#
# Requires, in the device YAML:
#   substitutions:
#     ota_device: <name of this YAML file without .yaml>
#     # ota_base_url: https://something-else.example  # only to override the
#     #   add-on's configured base_url for this one device
#   esphome:
#     project:
#       name: "you.something"
#       version: "1.0.0"      # bump this to offer an update
#
#   packages:
#     ota: !include {package_dir}/{update_file}
#
# Without an esphome.project block this compares against the ESPHome
# release string instead and will not flag config-only changes.
#
# If Install ever fails with "Failed to parse JSON..." in the device log
# (ESPHome's http_request does not decompress gzip, and some proxy/CDN
# configurations compress the manifest response), switch to
# {package_dir}/{button_file} instead — it never parses JSON, at the cost
# of no version tracking. Both can't be !include-d together (both declare
# http_request:/ota:); use {package_dir}/{package_file} for both at once.

substitutions:
  ota_base_url: {base_url}

http_request:
  timeout: 60s

ota:
  - platform: http_request

update:
  - platform: http_request
    id: ota_update
    name: Firmware
    source: ${{ota_base_url}}/local/{publish_dir}/${{ota_device}}.json
    update_interval: 6h
"""

BUTTON_PACKAGE = """\
{header}
# For devices ESPHome's own local/mDNS OTA can't reach (typically: outside
# your LAN, reachable only through your remote/cloud-tunnel URL). A device on
# the same network as Home Assistant should just use ESPHome's built-in OTA —
# it doesn't need this at all.
#
# Adds a "Firmware Update" button: no version tracking, no project.version
# needed — pressing it always installs whatever is currently published.
#
# Requires, in the device YAML:
#   substitutions:
#     ota_device: <name of this YAML file without .yaml>
#     # ota_base_url: https://something-else.example  # only to override the
#     #   add-on's configured base_url for this one device
#
#   packages:
#     ota: !include {package_dir}/{button_file}
#
# url/md5_url carry a random ?r= on every press (random_uint32(), evaluated
# fresh each call) so a caching proxy in front of Home Assistant — a
# Cloudflare tunnel, for instance — never has a reason to serve back a
# stale firmware/md5 pair.
#
# This button's id is `ota_flash_button` — press it programmatically from
# anything else in the device YAML with the button.press action, instead of
# duplicating the ota.http_request.flash call. E.g. to flash from a
# physical GPIO button instead of (or in addition to) the generated Home
# Assistant button:
#
#   button:
#     - platform: gpio
#       pin: GPIO0
#       name: Flash Button
#       on_press:
#         - button.press: ota_flash_button
#
# Want an Update entity too? Both can't be !include-d together (both
# declare http_request:/ota:); use {package_dir}/{package_file} for both
# at once instead of this file.

substitutions:
  ota_base_url: {base_url}

http_request:
  timeout: 60s

ota:
  - platform: http_request

button:
  - platform: template
    id: ota_flash_button
    name: Firmware Update
    entity_category: config
    on_press:
      - ota.http_request.flash:
          url: !lambda |-
            return std::string("${{ota_base_url}}/local/{publish_dir}/${{ota_device}}.ota.bin?r=") + std::to_string(random_uint32());
          md5_url: !lambda |-
            return std::string("${{ota_base_url}}/local/{publish_dir}/${{ota_device}}.ota.bin.md5?r=") + std::to_string(random_uint32());
"""

OTA_PACKAGE = """\
{header}
# For devices ESPHome's own local/mDNS OTA can't reach (typically: outside
# your LAN, reachable only through your remote/cloud-tunnel URL). A device on
# the same network as Home Assistant should just use ESPHome's built-in OTA —
# it doesn't need this at all.
#
# Both entities together — an "Update" entity (recommended: version
# comparison, Install in HA) and a "Firmware Update" button (fallback for
# the rare proxy/CDN JSON-mangling case, see {package_dir}/{update_file}).
# Want only one? Use {package_dir}/{update_file} or
# {package_dir}/{button_file} instead — smaller, and the filename says
# exactly what you're getting.
#
# Requires, in the device YAML:
#   substitutions:
#     ota_device: <name of this YAML file without .yaml>
#     # ota_base_url: https://something-else.example  # only to override the
#     #   add-on's configured base_url for this one device
#   esphome:
#     project:
#       name: "you.something"
#       version: "1.0.0"      # bump this to offer an update
#
#   packages:
#     ota: !include {package_dir}/{package_file}
#
# Without an esphome.project block the Update entity compares against the
# ESPHome release string and will not flag config-only changes. The button
# still works either way.
#
# This button's id is `ota_flash_button` — press it programmatically from
# anything else in the device YAML with the button.press action, instead of
# duplicating the ota.http_request.flash call. E.g. to flash from a
# physical GPIO button instead of (or in addition to) the generated Home
# Assistant button:
#
#   button:
#     - platform: gpio
#       pin: GPIO0
#       name: Flash Button
#       on_press:
#         - button.press: ota_flash_button

substitutions:
  ota_base_url: {base_url}

http_request:
  timeout: 60s

ota:
  - platform: http_request

update:
  - platform: http_request
    id: ota_update
    name: Firmware
    source: ${{ota_base_url}}/local/{publish_dir}/${{ota_device}}.json
    update_interval: 6h

button:
  - platform: template
    id: ota_flash_button  # referenced by `button.press: ota_flash_button` — see header
    name: Firmware Update
    entity_category: config
    on_press:
      - ota.http_request.flash:
          url: !lambda |-
            return std::string("${{ota_base_url}}/local/{publish_dir}/${{ota_device}}.ota.bin?r=") + std::to_string(random_uint32());
          md5_url: !lambda |-
            return std::string("${{ota_base_url}}/local/{publish_dir}/${{ota_device}}.ota.bin.md5?r=") + std::to_string(random_uint32());
"""


def write_packages(esphome_config_dir: Path, base_url: str, publish_dir: str) -> list[Path]:
    """(Re)write all three package files. Returns the paths written."""
    target = esphome_config_dir / PACKAGE_DIR
    target.mkdir(parents=True, exist_ok=True)

    fields = {
        "header": HEADER,
        "base_url": base_url.rstrip("/"),
        "publish_dir": publish_dir,
        "package_dir": PACKAGE_DIR,
        "package_file": PACKAGE_FILE,
        "update_file": UPDATE_FILE,
        "button_file": BUTTON_FILE,
    }
    written = []
    for filename, template in (
        (UPDATE_FILE, UPDATE_PACKAGE),
        (BUTTON_FILE, BUTTON_PACKAGE),
        (PACKAGE_FILE, OTA_PACKAGE),
    ):
        path = target / filename
        path.write_text(template.format(**fields), encoding="utf-8")
        written.append(path)

    LOG.info("Wrote ESPHome packages to %s", target)
    return written


def _project_block(node: str, published_version: str | None) -> str:
    """The esphome.project block, shared by the update-only and combined snippets.

    ``name`` defaults to the device's own node name rather than a fixed
    placeholder — every device gets a distinct one for free, nothing to
    remember to change. ``version`` mirrors whatever's actually published
    for this node when there is one (the number to bump *from*), instead of
    always resetting to 1.0.0 and silently un-doing whatever version scheme
    is already in use.
    """
    version = published_version or "1.0.0"
    comment = "  # bump this to publish a new update" if published_version else "   # bump to publish an update"
    return (
        f"esphome:\n"
        f"  project:\n"
        f'    name: "local.{node}"\n'
        f'    version: "{version}"{comment}\n'
    )


def single_entity_snippets(node: str, published_version: str | None = None) -> dict[str, str]:
    """Device-YAML snippets for update.yaml / flash_button.yaml alone."""
    header = f"substitutions:\n  ota_device: {node}\n\npackages:\n"
    update = (
        header
        + f"  ota: !include {PACKAGE_DIR}/{UPDATE_FILE}\n\n"
        + _project_block(node, published_version)
    )
    button = (
        header
        + f"  ota: !include {PACKAGE_DIR}/{BUTTON_FILE}\n\n"
        + f"# This button's id is ota_flash_button. Trigger the same flash from\n"
        f"# another button (e.g. a physical GPIO button) instead of duplicating\n"
        f"# the ota.http_request.flash call:\n"
        f"#\n"
        f"# button:\n"
        f"#   - platform: gpio\n"
        f"#     pin: GPIO0\n"
        f"#     name: Flash Button\n"
        f"#     on_press:\n"
        f"#       - button.press: ota_flash_button\n"
    )
    return {"update": update, "button": button}


def snippet(node: str, published_version: str | None = None) -> str:
    """The copy-paste block shown in the UI for one device — both entities."""
    return (
        f"substitutions:\n"
        f"  ota_device: {node}\n"
        f"\npackages:\n"
        f"  ota: !include {PACKAGE_DIR}/{PACKAGE_FILE}\n"
        f"\n{_project_block(node, published_version)}"
        f"\n# This button's id is ota_flash_button. Trigger the same flash from\n"
        f"# another button (e.g. a physical GPIO button) instead of duplicating\n"
        f"# the ota.http_request.flash call:\n"
        f"#\n"
        f"# button:\n"
        f"#   - platform: gpio\n"
        f"#     pin: GPIO0\n"
        f"#     name: Flash Button\n"
        f"#     on_press:\n"
        f"#       - button.press: ota_flash_button\n"
        f"\n# On a memory-constrained board (typically ESP8266), TLS certificate\n"
        f"# verification can be too much for its RAM. Uncomment to skip it:\n"
        f"# http_request:\n"
        f"#   verify_ssl: false\n"
    )
