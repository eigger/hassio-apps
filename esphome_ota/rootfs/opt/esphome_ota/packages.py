"""Generate the ESPHome packages users include in their device configs.

Three files in ``ota_server/``, each named for exactly what it contains —
the filename *is* the choice, no need to open it to know what you're
including:

* ``update.yaml`` — an ``update:`` entity only. Recommended: version
  tracking + an Install button in HA. The per-device wrapper supplies
  ``esphome.project`` so the device YAML does not.
* ``flash_button.yaml`` — a force-install button only. No version
  comparison; press it and the current published firmware is installed.
  The fallback for the rare case a proxy/CDN in front of Home Assistant
  mangles the Update entity's JSON manifest fetch (gzip compression, seen
  with some Cloudflare configurations — see DOCS.md).
* ``ota.yaml`` — both together, for a device that wants both entities.
  Only exists because ``update.yaml`` and ``flash_button.yaml`` can't be
  ``!include``d in the same device config — both declare ``http_request:``/
  ``ota:``, and ESPHome doesn't merge two packages' same-named top-level
  keys.
"""

from __future__ import annotations

import logging
import re
from pathlib import Path

from metadata import NODE_RE

# ESPHome project.name is "{author}.{project}" and capped at 32 characters.
_PROJECT_NAME_MAX = 32


def project_name(node: str) -> str:
    """``local.<stem>`` trimmed to ESPHome's 32-character project.name limit."""
    name = f"local.{node}"
    return name if len(name) <= _PROJECT_NAME_MAX else name[:_PROJECT_NAME_MAX]


def _wrapper_node(filename: str) -> str:
    for suffix in (".update.yaml", ".button.yaml", ".yaml"):
        if filename.endswith(suffix):
            return filename[: -len(suffix)]
    return filename


LOG = logging.getLogger("packages")

PACKAGE_DIR = "ota_server"
DEVICES_DIR = "devices"
PACKAGE_FILE = "ota.yaml"
UPDATE_FILE = "update.yaml"
BUTTON_FILE = "flash_button.yaml"

HEADER = """\
# ---------------------------------------------------------------------------
# Generated by the ESPHome OTA Publisher add-on. Do not edit — it is rewritten
# whenever the add-on starts or its options change.
# ---------------------------------------------------------------------------
"""

UPDATE_PACKAGE = """\
{header}
# For devices ESPHome's own local/mDNS OTA can't reach (typically: outside
# your LAN, reachable only through your remote/cloud-tunnel URL). A device on
# the same network as Home Assistant should just use ESPHome's built-in OTA —
# it doesn't need this at all.
#
# Adds an "Update" entity: version comparison, Install button in HA.
#
# Include the per-device wrapper (slug = YAML filename without .yaml):
#   packages:
#     ota: !include {package_dir}/{devices_dir}/livingroom.update.yaml
# The wrapper sets ota_device and esphome.project; the device YAML does
# not need those. Legacy: substitutions.ota_device + !include
# {package_dir}/{update_file}
#
# If Install ever fails with "Failed to parse JSON..." in the device log
# (ESPHome's http_request does not decompress gzip, and some proxy/CDN
# configurations compress the manifest response), switch to
# {package_dir}/{button_file} instead — it never parses JSON, at the cost
# of no version tracking. Both can't be !include-d together (both declare
# http_request:/ota:); use {package_dir}/{package_file} for both at once.

substitutions:
  ota_base_url: {base_url}

http_request:
  timeout: 60s

ota:
  - platform: http_request

update:
  - platform: http_request
    id: ota_update
    name: Firmware
    source: ${{ota_base_url}}/local/{publish_dir}/${{ota_device}}.json
    update_interval: 6h
"""

BUTTON_PACKAGE = """\
{header}
# For devices ESPHome's own local/mDNS OTA can't reach (typically: outside
# your LAN, reachable only through your remote/cloud-tunnel URL). A device on
# the same network as Home Assistant should just use ESPHome's built-in OTA —
# it doesn't need this at all.
#
# Adds a "Firmware Update" button: no version tracking, no project.version
# needed — pressing it always installs whatever is currently published.
#
# Include the per-device wrapper (slug = YAML filename without .yaml):
#   packages:
#     ota: !include {package_dir}/{devices_dir}/livingroom.button.yaml
# The wrapper sets ota_device; the device YAML does not need that substitution.
# Legacy: substitutions.ota_device + !include {package_dir}/{button_file}
#
# url/md5_url carry a random ?r= on every press (random_uint32(), evaluated
# fresh each call) so a caching proxy in front of Home Assistant — a
# Cloudflare tunnel, for instance — never has a reason to serve back a
# stale firmware/md5 pair.
#
# This button's id is `ota_flash_button` — press it programmatically from
# anything else in the device YAML with the button.press action, instead of
# duplicating the ota.http_request.flash call. E.g. to flash from a
# physical GPIO button instead of (or in addition to) the generated Home
# Assistant button:
#
#   button:
#     - platform: gpio
#       pin: GPIO0
#       name: Flash Button
#       on_press:
#         - button.press: ota_flash_button
#
# Want an Update entity too? Both can't be !include-d together (both
# declare http_request:/ota:); use {package_dir}/{package_file} for both
# at once instead of this file.

substitutions:
  ota_base_url: {base_url}

http_request:
  timeout: 60s

ota:
  - platform: http_request

button:
  - platform: template
    id: ota_flash_button
    name: Firmware Update
    entity_category: config
    on_press:
      - ota.http_request.flash:
          url: !lambda |-
            return std::string("${{ota_base_url}}/local/{publish_dir}/${{ota_device}}.ota.bin?r=") + std::to_string(random_uint32());
          md5_url: !lambda |-
            return std::string("${{ota_base_url}}/local/{publish_dir}/${{ota_device}}.ota.bin.md5?r=") + std::to_string(random_uint32());
"""

