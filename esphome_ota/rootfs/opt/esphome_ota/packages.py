def write_packages(esphome_config_dir: Path, base_url: str, publish_dir: str) -> list[Path]:
    """(Re)write all three package files. Returns the paths written."""
    target = esphome_config_dir / PACKAGE_DIR
    target.mkdir(parents=True, exist_ok=True)

    fields = {
        "header": HEADER,
        "base_url": base_url.rstrip("/"),
        "publish_dir": publish_dir,
        "package_dir": PACKAGE_DIR,
        "devices_dir": DEVICES_DIR,
        "package_file": PACKAGE_FILE,
        "update_file": UPDATE_FILE,
        "button_file": BUTTON_FILE,
    }
    written = []
    for filename, template in (
        (UPDATE_FILE, UPDATE_PACKAGE),
        (BUTTON_FILE, BUTTON_PACKAGE),
        (PACKAGE_FILE, OTA_PACKAGE),
    ):
        path = target / filename
        path.write_text(template.format(**fields), encoding="utf-8")
        written.append(path)

    LOG.info("Wrote ESPHome packages to %s", target)
    return written


DEVICE_WRAPPER = """\
{header}
# Per-device wrapper. Include this from {node}.yaml:
#
#   packages:
#     ota: !include {package_dir}/{devices_dir}/{wrapper_name}
#
# Sets ota_device from the YAML filename and esphome.project so the device
# YAML does not need either. Version is raised when the next compile is
# prepared (snippet), after the previous build has been published.
# Edit the version in the add-on UI to use a different value.
substitutions:
  ota_device: {node}

{project_block}packages:
  ota: !include {shared_include}
"""

PROJECT_BLOCK = """\
esphome:
  project:
    name: "{project_name}"
    version: "{version}"

"""


def bump_version(version: str) -> str:
    """Increment the last numeric run: 1.0.0 → 1.0.1, 2025.8.0 → 2025.8.1."""
    text = (version or "").strip().replace('"', "")
    if not text:
        return "1.0.0"
    parts = re.split(r"(\d+)", text)
    for i in range(len(parts) - 1, -1, -1):
        if parts[i].isdigit():
            parts[i] = str(int(parts[i]) + 1)
            return "".join(parts)
    return f"{text}.1"


def next_firmware_version(
    own: str | None,
    published: str | None,
    current_wrapper: str | None,
    bump: bool = False,
    override: str | None = None,
) -> str:
    """Version compiled into firmware via the generated wrapper.

    Device YAML does not need ``project.version``. The add-on fills this
    automatically and the UI can override it. We only increment when
    preparing the next compile (snippet) and the current wrapper version is
    already published — so compile-then-upload still matches the bin, and
    re-uploading the same bin does not jump the manifest ahead of it.
    """
    if override:
        return override.replace('"', "").strip()
    current = (current_wrapper or own or "").replace('"', "").strip()
    published = (published or "").replace('"', "").strip() or None
    if bump and published and (not current or current == published):
        return bump_version(published)
    return current or published or "1.0.0"


def normalize_version(version: str) -> str | None:
    """Return a wrapper-safe version string, or None if empty/invalid."""
    text = (version or "").strip().replace('"', "").replace("'", "")
    if not text or any(ch in text for ch in "\n\r\t"):
        return None
    if len(text) > 64:
        return None
    return text


def write_one_device_wrapper(
    esphome_config_dir: Path,
    node: str,
    version: str,
) -> list[Path]:
    """Write the three wrappers for one published/snippet device. Does not touch others."""
    if not NODE_RE.match(node):
        return []
    target = esphome_config_dir / PACKAGE_DIR / DEVICES_DIR
    target.mkdir(parents=True, exist_ok=True)
    version = (version or "1.0.0").replace('"', "") or "1.0.0"
    project_block = PROJECT_BLOCK.format(project_name=project_name(node), version=version)
    written: list[Path] = []
    for suffix, shared in (
        ("", PACKAGE_FILE),
        (".update", UPDATE_FILE),
        (".button", BUTTON_FILE),
    ):
        wrapper_name = f"{node}{suffix}.yaml"
        path = target / wrapper_name
        path.write_text(
            DEVICE_WRAPPER.format(
                header=HEADER,
                node=node,
                project_block=project_block,
                package_dir=PACKAGE_DIR,
                devices_dir=DEVICES_DIR,
                wrapper_name=wrapper_name,
                shared_include=f"../{shared}",
            ),
            encoding="utf-8",
        )
        written.append(path)
    return written


def write_device_wrappers(
    esphome_config_dir: Path,
    devices: list[dict[str, str]],
    keep_stems: set[str] | None = None,
) -> list[Path]:
    """Write one wrapper per device YAML stem so include path == publish slug.

    Wrappers for *keep_stems* that we could not refresh (parse failed) are
    left in place so a transient YAML error cannot delete them.
    """
    target = esphome_config_dir / PACKAGE_DIR / DEVICES_DIR
    target.mkdir(parents=True, exist_ok=True)
    keep_stems = keep_stems or set()

    kinds = (
        ("", PACKAGE_FILE),
        (".update", UPDATE_FILE),
        (".button", BUTTON_FILE),
    )
    wanted: set[str] = set()
    written: list[Path] = []
    for item in devices:
        node = item["node"]
        version = (item.get("version") or "1.0.0").replace('"', "") or "1.0.0"
        if not NODE_RE.match(node):
            continue
        project_block = PROJECT_BLOCK.format(
            project_name=project_name(node), version=version
        )
        for suffix, shared in kinds:
            wrapper_name = f"{node}{suffix}.yaml"
            wanted.add(wrapper_name)
            path = target / wrapper_name
            path.write_text(
                DEVICE_WRAPPER.format(
                    header=HEADER,
                    node=node,
                    project_block=project_block,
                    package_dir=PACKAGE_DIR,
                    devices_dir=DEVICES_DIR,
                    wrapper_name=wrapper_name,
                    shared_include=f"../{shared}",
                ),
                encoding="utf-8",
            )
            written.append(path)

    for existing in target.glob("*.yaml"):
        if existing.name in wanted:
            continue
        if _wrapper_node(existing.name) in keep_stems:
            continue
        existing.unlink()
        LOG.info("Removed stale device wrapper %s", existing.name)

    LOG.info("Wrote %s device wrappers under %s", len(written), target)
    return written


def device_wrapper_exists(esphome_config_dir: Path, node: str) -> bool:
    return (esphome_config_dir / PACKAGE_DIR / DEVICES_DIR / f"{node}.yaml").is_file()


def delete_device_wrappers(esphome_config_dir: Path, node: str) -> None:
    target = esphome_config_dir / PACKAGE_DIR / DEVICES_DIR
    if not target.is_dir():
        return
    for suffix in ("", ".update", ".button"):
        (target / f"{node}{suffix}.yaml").unlink(missing_ok=True)


def _include_line(node: str, suffix: str = "") -> str:
    return f"packages:\n  ota: !include {PACKAGE_DIR}/{DEVICES_DIR}/{node}{suffix}.yaml\n"


def _project_block(node: str, published_version: str | None) -> str:
    """esphome.project for the legacy ota_device snippet (no wrapper file)."""
    version = next_firmware_version(None, published_version, published_version, bump=True)
    return (
        f"esphome:\n"
        f"  project:\n"
        f'    name: "{project_name(node)}"\n'
        f'    version: "{version}"\n'
    )


_FLASH_HINT = (
    "\n# This button's id is ota_flash_button. Trigger the same flash from\n"
    "# another button (e.g. a physical GPIO button) instead of duplicating\n"
    "# the ota.http_request.flash call:\n"
    "#\n"
    "# button:\n"
    "#   - platform: gpio\n"
    "#     pin: GPIO0\n"
    "#     name: Flash Button\n"
    "#     on_press:\n"
    "#       - button.press: ota_flash_button\n"
)

_SSL_HINT = (
    "\n# On a memory-constrained board (typically ESP8266), TLS certificate\n"
    "# verification can be too much for its RAM. Uncomment to skip it:\n"
    "# http_request:\n"
    "#   verify_ssl: false\n"
)


def single_entity_snippets(
    node: str,
    published_version: str | None = None,
    has_wrapper: bool = True,
    has_project: bool = True,
) -> dict[str, str]:
    """Device-YAML snippets for update.yaml / flash_button.yaml alone."""
    if has_wrapper:
        update = _include_line(node, ".update")
        button = _include_line(node, ".button") + _FLASH_HINT
        return {"update": update, "button": button}
    header = f"substitutions:\n  ota_device: {node}\n\npackages:\n"
    update = (
        header
        + f"  ota: !include {PACKAGE_DIR}/{UPDATE_FILE}\n\n"
        + _project_block(node, published_version)
    )
    button = header + f"  ota: !include {PACKAGE_DIR}/{BUTTON_FILE}\n" + _FLASH_HINT
    return {"update": update, "button": button}


def snippet(
    node: str,
    published_version: str | None = None,
    has_wrapper: bool = True,
    has_project: bool = True,
) -> str:
    """The copy-paste block shown in the UI."""
    if has_wrapper:
        note = (
            "\n# ota_device, http_request/ota, Update + flash button, and\n"
            "# esphome.project are in that include. Nothing else to paste.\n"
        )
        return _include_line(node) + note + _FLASH_HINT + _SSL_HINT
    return (
        f"substitutions:\n"
        f"  ota_device: {node}\n"
        f"\npackages:\n"
        f"  ota: !include {PACKAGE_DIR}/{PACKAGE_FILE}\n"
        f"\n{_project_block(node, published_version)}"
        + _FLASH_HINT
        + _SSL_HINT
    )
